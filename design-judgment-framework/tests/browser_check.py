from pathlib import Path
from playwright.sync_api import sync_playwright
p=Path(__file__).resolve().parent.parent
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True, executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 page.set_default_timeout(4000)
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content((p/"workspace-output/security-alert-review.html").read_text(),wait_until="load")
 page.screenshot(path=str(p/'workspace-output/new-desktop-preview.png'),full_page=False)
 print('title',page.title())
 print('nav',page.locator('.nav-link').count(),'artifacts',page.locator('.artifact').count())
 page.get_by_role('button',name='Navigation explorations').click()
 print('visual buttons',page.get_by_role('button',name='Enlarge information architecture: A · Alert-centered').count(),page.locator('.visual-footer .btn').count())
 print('review status',page.locator('select').first.evaluate('(el)=>({bg:getComputedStyle(el).backgroundColor,color:getComputedStyle(el).color,scheme:getComputedStyle(el).colorScheme})'))
 page.get_by_role('button',name='Enlarge information architecture: A · Alert-centered').click()
 print('dialog visible',page.locator('#visualDialog').evaluate('(el)=>el.open'))
 print('zoom',page.locator('#zoomValue').inner_text())
 original=page.locator('#viewerContent').bounding_box()['width']
 page.get_by_role('button',name='Zoom in').click()
 enlarged=page.locator('#viewerContent').bounding_box()['width']
 assert enlarged>original*1.2,(original,enlarged)
 print('zoom after',page.locator('#zoomValue').inner_text(),'widths',round(original),round(enlarged))
 page.keyboard.press('Escape')
 print('closed after escape',page.locator('#visualDialog').evaluate('(el)=>el.open'))
 # navigation and review 
 page.get_by_role('button',name='Triage interface concepts').click()
 print('concepts page',page.locator('h1').first.inner_text())
 page.get_by_role('button',name='Enlarge wireframe: Concept 1 · Queue first').first.click()
 print('wireframe modal',page.locator('#visualDialog').evaluate('(el)=>el.open'))
 page.get_by_role('button',name='Close').first.click()
 sel=page.locator('.field select').first
 sel.select_option('needs_revision')
 print('status selected',sel.input_value())
 page.locator('.field textarea').first.fill('Need more evidence of triage tasks')
 print('feedback note accepted',page.locator('.field textarea').first.input_value())
 page.get_by_role('button',name='Iteration policy').click()
 print('policy opens',page.locator('#policyDialog').evaluate('(el)=>el.open'))
 page.locator('#policyDialog input[type=range]').first.fill('5')
 print('policy value',page.locator('#policyDialog .policy-entry strong').first.inner_text())
 page.get_by_role('button',name='Close').first.click()
 print('errors',errors)
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
 mobile_errors=[]
 mobile.on('pageerror',lambda e:mobile_errors.append(str(e)))
 mobile.set_content((p/"workspace-output/security-alert-review.html").read_text(),wait_until="load")
 mobile.screenshot(path=str(p/'workspace-output/new-mobile-preview.png'),full_page=False)
 print('mobile body-scroll-width', mobile.evaluate('document.documentElement.scrollWidth'), 'viewport',mobile.evaluate('window.innerWidth'))
 mobile.get_by_role('button',name='Open project navigation').click()
 print('mobile nav open',mobile.locator('#sidebar').get_attribute('class'))
 mobile.get_by_role('button',name='Navigation explorations').click()
 print('mobile navigated',mobile.locator('h1').first.inner_text())
 mobile.get_by_role('button',name='Enlarge information architecture: A · Alert-centered').click()
 print('mobile dialog open',mobile.locator('#visualDialog').evaluate('(el)=>el.open'))
 mobile.screenshot(path=str(p/'workspace-output/new-mobile-viewer-preview.png'),full_page=False)
 mobile.get_by_role('button',name='Close').first.click()
 print('mobile errors',mobile_errors)
 mobile.locator('#mobileMore summary').click()
 print('mobile actions',mobile.locator('.more-panel button').all_text_contents())
 mobile.locator('#mobilePolicyBtn').click()
 print('mobile policy accessible',mobile.locator('#policyDialog').evaluate('(e)=>e.open'))
 mobile.get_by_role('button',name='Close').first.click()
 example=browser.new_page(viewport={'width':1440,'height':900})
 example.set_content((p/'workspace-output/workspace-redesign-review.html').read_text(),wait_until='load')
 example.get_by_role('button',name='Visual QA & screenshots').click()
 print('image cards',example.locator('.image-card').count())
 example.get_by_role('button',name='Enlarge image: Redesigned desktop HTML workspace with grouped project navigation and a large artifact reading area').click()
 print('image viewer open',example.locator('#visualDialog').evaluate('(e)=>e.open'),'img src',example.locator('#viewerContent img').get_attribute('src')[:30])
 example.screenshot(path=str(p/'workspace-output/new-image-viewer-preview.png'),full_page=False)
 example.get_by_role('button',name='Close').first.click()
 print("Browser smoke checks passed")
 browser.close()
